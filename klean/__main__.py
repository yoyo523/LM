"""Compile and run a Klean ``.kln`` source file."""
from __future__ import annotations

import argparse
from dataclasses import asdict
import json
from pathlib import Path
import sys

from .compiler import compile_source
from .vm import KleanRuntimeError, execute


def positive_int(value: str) -> int:
    number = int(value)
    if number <= 0:
        raise argparse.ArgumentTypeError("must be a positive integer")
    return number


def main() -> int:
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("source", type=Path, help="Klean source file")
    cli.add_argument("--tokens", action="store_true", help="print the token stream")
    cli.add_argument("--ast", action="store_true", help="print the AST as JSON")
    cli.add_argument("--bytecode", action="store_true", help="print generated bytecode")
    cli.add_argument("--no-run", action="store_true", help="compile without executing")
    cli.add_argument("--max-steps", type=positive_int, default=1_000_000,
                     help="maximum VM instructions (default: 1000000)")
    cli.add_argument("--max-frames", type=positive_int, default=1_000,
                     help="maximum active function calls (default: 1000)")
    args = cli.parse_args()

    try:
        source = args.source.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as error:
        print(f"{args.source}: {error}", file=sys.stderr)
        return 1

    result = compile_source(source)
    if result.diagnostics:
        for error in result.diagnostics:
            print(
                f"{args.source}:{error.line}:{error.column}: {error.message}",
                file=sys.stderr,
            )
        return 1

    if args.tokens:
        for token in result.tokens:
            print(f"{token.line}:{token.column}\t{token.kind}\t{token.text!r}")
    if args.ast:
        try:
            print(json.dumps(asdict(result.ast), indent=2))
        except RecursionError:
            print(f"{args.source}: AST is too deeply nested to display", file=sys.stderr)
            return 1
    if args.bytecode:
        print(result.bytecode.format())

    if not args.no_run:
        try:
            execute(result.bytecode, max_steps=args.max_steps, max_frames=args.max_frames)
        except KleanRuntimeError as error:
            print(f"{args.source}: runtime error: {error}", file=sys.stderr)
            return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
