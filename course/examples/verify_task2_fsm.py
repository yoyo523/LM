"""Compare the Task 2 diagram with strings derived from the given grammar."""

from collections import deque
from itertools import product
from pathlib import Path
from xml.etree import ElementTree


root = ElementTree.parse(Path(__file__).with_name("task2_fsm.svg")).getroot()
states = {node.attrib["data-state"] for node in root.iter()
          if "data-state" in node.attrib}
initial = [node.attrib["data-state"] for node in root.iter()
           if node.get("data-initial") == "true"]
accepting = {node.attrib["data-state"] for node in root.iter()
             if node.get("data-accepting") == "true"}
assert len(initial) == 1
transitions = {}
for edge in root.iter():
    if "data-from" not in edge.attrib:
        continue
    source, target = edge.get("data-from"), edge.get("data-to")
    assert source in states and target in states
    label = next(child for child in edge if child.tag.endswith("}text"))
    symbols = edge.get("data-symbols").split(",")
    assert "".join(label.itertext()).replace(" ", "").split(",") == symbols
    for symbol in symbols:
        assert (source, symbol) not in transitions, "Non-deterministic edge"
        transitions[source, symbol] = target
assert set(transitions) == set(product(states, "ab")), "Incomplete DFA"


def accepts(word):
    state = initial[0]
    for symbol in word:
        state = transitions[state, symbol]
    return state in accepting


# Generate terminal strings by rewriting the original productions.
productions = {"S": ("aA", "bB"), "A": ("aS", "b"), "B": ("bS", "a")}
max_length = 12
pending = deque(["S"])
seen = set()
generated = set()
while pending:
    form = pending.popleft()
    if form in seen or sum(ch in "ab" for ch in form) > max_length:
        continue
    seen.add(form)
    position = next((i for i, ch in enumerate(form) if ch in productions), None)
    if position is None:
        generated.add(form)
        continue
    for replacement in productions[form[position]]:
        pending.append(form[:position] + replacement + form[position + 1:])

checked = 0
for length in range(max_length + 1):
    for chars in product("ab", repeat=length):
        word = "".join(chars)
        assert accepts(word) == (word in generated), f"Incorrect result for {word!r}"
        checked += 1
print(f"PASS: complete DFA; checked {checked:,} strings of lengths 0-{max_length}")
print(f"against {len(generated)} terminal strings generated by the six productions.")
for word in ["ab", "ba", "aaab", "bbba", "aabbab", "", "a", "aa", "bb", "abab"]:
    print(f"{word!r}: {'accept' if accepts(word) else 'reject'}")
